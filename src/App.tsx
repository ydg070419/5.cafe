// ==========================================
// 2. 메인 애플리케이션 컴포넌트
// ==========================================

export default function App() {
  // ----------------------------------------
  // 입력 폼 상태(State) 관리
  // ----------------------------------------
  const [customerName, setCustomerName] = useState<string>(''); // 이름 (필수)
  const [phoneNumber, setPhoneNumber] = useState<string>('');   // 전화번호
  const [selectedDrinkId, setSelectedDrinkId] = useState<string>(''); // 선택된 음료 ID
  const [selectedSize, setSelectedSize] = useState<'S' | 'M' | 'L'>('M'); // 사이즈 (기본값 M)
  const [selectedOptions, setSelectedOptions] = useState<string[]>([]); // 선택된 추가 옵션 ID 배열
  const [quantity, setQuantity] = useState<number>(1); // 수량 (기본값 1, 최소 1, 최대 10)
  const [requests, setRequests] = useState<string>(''); // 요청사항

  // 주문 확인 메시지 상태
  const [confirmationMessage, setConfirmationMessage] = useState<string | null>(null);
  // 검증 에러 메시지 상태 (이름 미입력, 음료 미선택 등)
  const [validationError, setValidationError] = useState<string | null>(null);

  // Supabase 연동 상태 관리
  const [isConfigModalOpen, setIsConfigModalOpen] = useState(false);
  const [connectionStatus, setConnectionStatus] = useState<'connected' | 'not_configured' | 'error' | 'checking'>('checking');
  const [connectionMessage, setConnectionMessage] = useState<string>('');
  const [isSubmitting, setIsSubmitting] = useState<boolean>(false);
  const [isLoadingOrders, setIsLoadingOrders] = useState<boolean>(false);

  // 최근 주문 게시판 목록
  const [orderList, setOrderList] = useState<OrderItem[]>([
    {
      id: 'demo-1',
      createdAt: '방금 전',
      customerName: '홍길동',
      phoneNumber: '010-1234-5678',
      drinkName: '카페라떼',
      drinkPrice: 4000,
      size: 'M',
      sizePrice: 500,
      options: ['샷 추가'],
      optionsPrice: 500,
      quantity: 1,
      requests: '따뜻하게 데워주세요.',
      totalPrice: 5000,
      orderStatus: '접수완료',
    },
  ]);

  // 활성 탭: 'order' (주문하기) | 'board' (주문 게시판)
  const [activeTab, setActiveTab] = useState<'order' | 'board'>('order');

  // 날짜/시간 포맷터 함수
  const formatDateTime = (isoString?: string) => {
    if (!isoString) return '방금 전';
    try {
      const date = new Date(isoString);
      return date.toLocaleTimeString('ko-KR', {
        hour: '2-digit',
        minute: '2-digit',
        second: '2-digit',
      });
    } catch {
      return isoString;
    }
  };

  // DB Row -> UI OrderItem 변환 함수
  const convertDbRowToOrder = (row: CafeMenuRow): OrderItem => {
    return {
      id: row.id,
      dbId: row.id,
      createdAt: formatDateTime(row.created_at),
      customerName: row.customer_name,
      phoneNumber: row.phone_number || '',
      drinkName: row.drink_name,
      drinkPrice: row.drink_price,
      size: (row.size as 'S' | 'M' | 'L') || 'M',
      sizePrice: row.size_price,
      options: Array.isArray(row.options) ? row.options : [],
      optionsPrice: row.options_price,
      quantity: row.quantity,
      requests: row.requests || '',
      totalPrice: row.total_price,
      orderStatus: (row.order_status as '접수완료' | '제조중' | '완료') || '접수완료',
    };
  };

  // ----------------------------------------
  // Supabase 주문 데이터 불러오기
  // ----------------------------------------
  const loadOrdersFromDb = useCallback(async () => {
    const config = getSupabaseConfig();
    if (!config.url || !config.anonKey) {
      setConnectionStatus('not_configured');
      return;
    }

    setIsLoadingOrders(true);
    const { data, error } = await fetchOrders();
    setIsLoadingOrders(false);

    if (error) {
      console.warn('주문 불러오기 실패:', error);
      return;
    }

    if (data && data.length > 0) {
      setOrderList(data.map(convertDbRowToOrder));
    } else {
      setOrderList([]);
    }
  }, []);

  // ----------------------------------------
  // Supabase 연결 상태 점검
  // ----------------------------------------
  const checkConnection = useCallback(async () => {
    setConnectionStatus('checking');
    const result = await checkSupabaseConnection();
    setConnectionMessage(result.message);

    if (result.connected && result.tableExists) {
      setConnectionStatus('connected');
      await loadOrdersFromDb();
    } else if (result.connected && !result.tableExists) {
      setConnectionStatus('error');
    } else {
      const config = getSupabaseConfig();
      if (!config.url) {
        setConnectionStatus('not_configured');
      } else {
        setConnectionStatus('error');
      }
    }
  }, [loadOrdersFromDb]);

  // 최초 로드 시 연결 확인 및 실시간 구독 설정
  useEffect(() => {
    checkConnection();

    // Supabase Realtime 구독 연결
    const unsubscribe = subscribeToOrders(() => {
      loadOrdersFromDb();
    });

    return () => {
      unsubscribe();
    };
  }, [checkConnection, loadOrdersFromDb]);

  // ----------------------------------------
  // 실시간 예상 금액 계산 (JavaScript 기능)
  // ----------------------------------------
  const estimatedPrice = useMemo(() => {
    // 1. 선택된 음료 기본 가격 (선택되지 않았으면 0원)
    const drinkObj = DRINK_LIST.find((d) => d.id === selectedDrinkId);
    const drinkPrice = drinkObj ? drinkObj.price : 0;

    // 2. 사이즈 추가 금액
    const sizeObj = SIZE_OPTIONS.find((s) => s.id === selectedSize);
    const sizePrice = sizeObj ? sizeObj.price : 0;

    // 3. 추가 옵션 금액 합계
    const optionsPrice = selectedOptions.reduce((sum, optId) => {
      const opt = EXTRA_OPTIONS.find((o) => o.id === optId);
      return sum + (opt ? opt.price : 0);
    }, 0);

    // 4. (음료가격 + 사이즈추가금 + 옵션합계) * 수량
    const singleItemPrice = drinkPrice + sizePrice + optionsPrice;
    return singleItemPrice * Math.max(1, quantity);
  }, [selectedDrinkId, selectedSize, selectedOptions, quantity]);

  // ----------------------------------------
  // 추가 옵션 토글 핸들러
  // ----------------------------------------
  const handleOptionChange = (optionId: string) => {
    setSelectedOptions((prev) =>
      prev.includes(optionId)
        ? prev.filter((id) => id !== optionId)
        : [...prev, optionId]
    );
  };

  // ----------------------------------------
  // 다시 작성 (초기화) 버튼 핸들러
  // ----------------------------------------
  const handleReset = () => {
    setCustomerName('');
    setPhoneNumber('');
    setSelectedDrinkId('');
    setSelectedSize('M'); // 기본값 M 복구
    setSelectedOptions([]);
    setQuantity(1); // 기본값 1 복구
    setRequests('');
    setConfirmationMessage(null);
    setValidationError(null);
  };

  // ----------------------------------------
  // 주문 상태 변경 핸들러
  // ----------------------------------------
  const handleUpdateStatus = async (order: OrderItem, nextStatus: '접수완료' | '제조중' | '완료') => {
    if (order.dbId && connectionStatus === 'connected') {
      const { success, error } = await updateOrderStatus(order.dbId, nextStatus);
      if (!success) {
        alert(`상태 변경에 실패했습니다: ${error?.message || ''}`);
        return;
      }
      await loadOrdersFromDb();
    } else {
      // 로컬 상태 업데이트
      setOrderList((prev) =>
        prev.map((item) =>
          item.id === order.id ? { ...item, orderStatus: nextStatus } : item
        )
      );
    }
  };

  // ----------------------------------------
  // 주문 삭제 핸들러
  // ----------------------------------------
  const handleDeleteOrder = async (order: OrderItem) => {
    if (!confirm(`${order.customerName}님의 주문을 삭제하시겠습니까?`)) {
      return;
    }

    if (order.dbId && connectionStatus === 'connected') {
      const { success, error } = await deleteOrder(order.dbId);
      if (!success) {
        alert(`주문 삭제 실패: ${error?.message || ''}`);
        return;
      }
      await loadOrdersFromDb();
    } else {
      setOrderList((prev) => prev.filter((item) => item.id !== order.id));
    }
  };

  // ----------------------------------------
  // 주문하기 버튼 클릭 핸들러 (유효성 검사 및 접수)
  // ----------------------------------------
  const handleSubmitOrder = async (e: React.FormEvent) => {
    e.preventDefault();
    setValidationError(null);

    // 유효성 검사 1: 이름이 비어있으면 "이름을 입력해주세요" 알림
    if (!customerName.trim()) {
      setValidationError('이름을 입력해주세요');
      alert('이름을 입력해주세요');
      return;
    }

    // 유효성 검사 2: 음료를 선택하지 않았으면 "음료를 선택해주세요" 알림
    if (!selectedDrinkId) {
      setValidationError('음료를 선택해주세요');
      alert('음료를 선택해주세요');
      return;
    }

    // 선택된 음료 정보 가져오기
    const selectedDrink = DRINK_LIST.find((d) => d.id === selectedDrinkId)!;
    const selectedSizeObj = SIZE_OPTIONS.find((s) => s.id === selectedSize)!;

    // 선택된 추가 옵션 라벨 목록 구성
    const selectedOptionLabels = selectedOptions
      .map((optId) => EXTRA_OPTIONS.find((o) => o.id === optId)?.label)
      .filter(Boolean) as string[];

    // 옵션 텍스트 형식화
    const optionsText =
      selectedOptionLabels.length > 0
        ? ` (${selectedOptionLabels.join(', ')})`
        : '';

    // 금액 콤마 표시 (toLocaleString 적용)
    const formattedPrice = estimatedPrice.toLocaleString();

    const optionsSum = selectedOptions.reduce((acc, optId) => {
      const item = EXTRA_OPTIONS.find((o) => o.id === optId);
      return acc + (item ? item.price : 0);
    }, 0);

    // Supabase가 연결되어 있는 경우 DB에 INSERT
    if (connectionStatus === 'connected') {
      setIsSubmitting(true);
      const { data, error } = await createOrder({
        customer_name: customerName.trim(),
        phone_number: phoneNumber.trim() || null,
        drink_name: selectedDrink.name,
        drink_price: selectedDrink.price,
        size: selectedSize,
        size_price: selectedSizeObj.price,
        options: selectedOptionLabels,
        options_price: optionsSum,
        quantity: quantity,
        requests: requests.trim() || null,
        total_price: estimatedPrice,
        order_status: '접수완료',
      });
      setIsSubmitting(false);

      if (error) {
        alert(`Supabase 주문 저장 중 오류가 발생했습니다: ${error.message}`);
        return;
      }

      const orderMessage = `⚡ [Supabase DB 저장 완료] ${customerName.trim()}님, ${selectedDrink.name} ${selectedSize}사이즈${optionsText} ${quantity}잔, 총 ${formattedPrice}원 주문이 접수되었습니다!`;
      setConfirmationMessage(orderMessage);

      if (data) {
        setOrderList((prev) => [convertDbRowToOrder(data), ...prev]);
      } else {
        await loadOrdersFromDb();
      }
    } else {
      // Supabase 미연결 시 로컬 상태에 임시 저장 (오프라인 모드)
      const orderMessage = `${customerName.trim()}님, ${selectedDrink.name} ${selectedSize}사이즈${optionsText} ${quantity}잔, 총 ${formattedPrice}원 주문이 접수되었습니다! (로컬 모드: 상단 'Supabase 연결'을 누르면 DB에 영구 저장됩니다)`;
      setConfirmationMessage(orderMessage);

      const newOrder: OrderItem = {
        id: `order-${Date.now()}`,
        createdAt: '방금 전',
        customerName: customerName.trim(),
        phoneNumber: phoneNumber.trim(),
        drinkName: selectedDrink.name,
        drinkPrice: selectedDrink.price,
        size: selectedSize,
        sizePrice: selectedSizeObj.price,
        options: selectedOptionLabels,
        optionsPrice: optionsSum,
        quantity: quantity,
        requests: requests.trim(),
        totalPrice: estimatedPrice,
        orderStatus: '접수완료',
      };

      setOrderList((prev) => [newOrder, ...prev]);
    }
  };

  return (
    <div className="min-h-screen bg-[#faf6f0] text-[#3e2723] py-6 px-4 flex flex-col items-center">
      {/* 
        ====================================================
        [전체 디자인 규격]
        - 최대 너비: 520px
        - 가운데 정렬
        - 둥근 모서리, 부드러운 그림자
        - 배경 베이지: #faf6f0, 포인트 브라운: #6b4226
        ====================================================
      */}
      <div className="w-full max-w-[520px] mx-auto bg-white rounded-2xl shadow-lg border border-[#ede0d4] overflow-hidden">
        
        {/* 상단 헤더 영역 */}
        <header className="pt-6 pb-5 px-6 text-center border-b border-[#f3ece2] bg-gradient-to-b from-[#faf6f0] to-white relative">
          
          {/* Supabase 연결 상태 배지 버튼 */}
          <div className="flex justify-end mb-2">
            <button
              type="button"
              onClick={() => setIsConfigModalOpen(true)}
              className={`inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-xs font-semibold transition-all border cursor-pointer ${
                connectionStatus === 'connected'
                  ? 'bg-emerald-50 text-emerald-700 border-emerald-200 hover:bg-emerald-100'
                  : connectionStatus === 'checking'
                  ? 'bg-amber-50 text-amber-700 border-amber-200 animate-pulse'
                  : connectionStatus === 'error'
                  ? 'bg-rose-50 text-rose-700 border-rose-200 hover:bg-rose-100'
                  : 'bg-amber-50 text-amber-800 border-amber-200 hover:bg-amber-100'
              }`}
              title="클릭하여 Supabase 연동 설정 열기"
            >
              <Database className="w-3.5 h-3.5" />
              <span className="flex items-center gap-1">
                <span
                  className={`w-2 h-2 rounded-full ${
                    connectionStatus === 'connected'
                      ? 'bg-emerald-500'
                      : connectionStatus === 'checking'
                      ? 'bg-amber-400'
                      : connectionStatus === 'error'
                      ? 'bg-rose-500'
                      : 'bg-amber-500'
                  }`}
                />
                {connectionStatus === 'connected'
                  ? 'Supabase 연결됨'
                  : connectionStatus === 'checking'
                  ? '연결 확인 중...'
                  : connectionStatus === 'error'
                  ? 'Supabase 확인 필요'
                  : 'Supabase 연결하기'}
              </span>
            </button>
          </div>

          <div className="text-5xl mb-2 select-none" role="img" aria-label="커피 로고">
            ☕
          </div>
          <h1 className="text-2xl font-bold tracking-tight text-[#6b4226]">
            바이브 카페
          </h1>
          <p className="text-sm text-[#8d6e63] mt-1 font-medium">
            당신의 하루에 바이브를 더하다
          </p>

          {/* 상단 빠른 네비게이션 탭 (주문하기 / 주문 게시판) */}
          <div className="flex items-center justify-center gap-2 mt-5">
            <button
              type="button"
              onClick={() => setActiveTab('order')}
              className={`px-4 py-1.5 text-xs font-semibold rounded-lg transition-all cursor-pointer ${
                activeTab === 'order'
                  ? 'bg-[#6b4226] text-white shadow-sm'
                  : 'bg-[#f7efe5] text-[#6b4226] hover:bg-[#ede0d4]'
              }`}
            >
              ☕ 주문서 작성
            </button>
            <button
              type="button"
              onClick={() => setActiveTab('board')}
              className={`px-4 py-1.5 text-xs font-semibold rounded-lg transition-all flex items-center gap-1 cursor-pointer ${
                activeTab === 'board'
                  ? 'bg-[#6b4226] text-white shadow-sm'
                  : 'bg-[#f7efe5] text-[#6b4226] hover:bg-[#ede0d4]'
              }`}
            >
              <ClipboardList className="w-3.5 h-3.5" />
              주문 게시판 ({orderList.length})
            </button>
          </div>
        </header>

        {/* 탭 1: 주문서 작성 폼 */}
        {activeTab === 'order' && (
          <main className="p-6">
            <form onSubmit={handleSubmitOrder} className="space-y-5">
              
              {/* 1. 이름 (필수, text) */}
              <div>
                <label 
                  htmlFor="customerName" 
                  className="block text-sm font-bold text-[#5d4037] mb-1.5"
                >
                  이름 <span className="text-red-500">*</span>
                </label>
                <input
                  id="customerName"
                  type="text"
                  placeholder="주문하시는 분의 성함을 입력하세요"
                  value={customerName}
                  onChange={(e) => setCustomerName(e.target.value)}
                  className="cafe-input"
                />
              </div>

              {/* 2. 전화번호 (tel) */}
              <div>
                <label 
                  htmlFor="phoneNumber" 
                  className="block text-sm font-bold text-[#5d4037] mb-1.5"
                >
                  전화번호
                </label>
                <input
                  id="phoneNumber"
                  type="tel"
                  placeholder="예: 010-1234-5678"
                  value={phoneNumber}
                  onChange={(e) => setPhoneNumber(e.target.value)}
                  className="cafe-input"
                />
              </div>

              {/* 3. 음료 선택 (드롭다운) */}
              <div>
                <label 
                  htmlFor="drinkSelect" 
                  className="block text-sm font-bold text-[#5d4037] mb-1.5"
                >
                  음료 선택 <span className="text-red-500">*</span>
                </label>
                <select
                  id="drinkSelect"
                  value={selectedDrinkId}
                  onChange={(e) => setSelectedDrinkId(e.target.value)}
                  className="cafe-input cursor-pointer"
                >
                  <option value="">-- 음료를 선택해주세요 --</option>
                  {DRINK_LIST.map((drink) => (
                    <option key={drink.id} value={drink.id}>
                      {drink.name} - {drink.price.toLocaleString()}원
                    </option>
                  ))}
                </select>
              </div>

              {/* 4. 사이즈 (라디오 버튼, 가로 배치) */}
              <div>
                <label className="block text-sm font-bold text-[#5d4037] mb-1.5">
                  사이즈 선택
                </label>
                <div className="flex flex-wrap items-center gap-4 bg-[#faf6f0] p-3 rounded-lg border border-[#ede0d4]">
                  {SIZE_OPTIONS.map((sizeOpt) => (
                    <label
                      key={sizeOpt.id}
                      htmlFor={`size-${sizeOpt.id}`}
                      className="inline-flex items-center gap-2 cursor-pointer select-none text-sm text-[#4e342e] font-medium"
                    >
                      <input
                        type="radio"
                        id={`size-${sizeOpt.id}`}
                        name="coffeeSize"
                        value={sizeOpt.id}
                        checked={selectedSize === sizeOpt.id}
                        onChange={() => setSelectedSize(sizeOpt.id)}
                        className="w-4 h-4 accent-[#6b4226] cursor-pointer"
                      />
                      <span>
                        {sizeOpt.label} ({sizeOpt.price > 0 ? `+${sizeOpt.price.toLocaleString()}원` : '+0원'})
                        {sizeOpt.id === 'M' && (
                          <span className="text-xs text-[#8d6e63] font-normal ml-1">
                            (기본)
                          </span>
                        )}
                      </span>
                    </label>
                  ))}
                </div>
              </div>

              {/* 5. 추가 옵션 (체크박스, 가로 배치) */}
              <div>
                <label className="block text-sm font-bold text-[#5d4037] mb-1.5">
                  추가 옵션
                </label>
                <div className="grid grid-cols-2 sm:flex sm:flex-wrap items-center gap-3 bg-[#faf6f0] p-3 rounded-lg border border-[#ede0d4]">
                  {EXTRA_OPTIONS.map((opt) => (
                    <label
                      key={opt.id}
                      htmlFor={`opt-${opt.id}`}
                      className="inline-flex items-center gap-2 cursor-pointer select-none text-sm text-[#4e342e]"
                    >
                      <input
                        type="checkbox"
                        id={`opt-${opt.id}`}
                        checked={selectedOptions.includes(opt.id)}
                        onChange={() => handleOptionChange(opt.id)}
                        className="w-4 h-4 accent-[#6b4226] rounded cursor-pointer"
                      />
                      <span>
                        {opt.label} ({opt.price > 0 ? `+${opt.price.toLocaleString()}원` : '+0원'})
                      </span>
                    </label>
                  ))}
                </div>
              </div>

              {/* 6. 수량 (number 타입, 최소 1, 최대 10, 기본값 1) */}
              <div>
                <label 
                  htmlFor="quantityInput" 
                  className="block text-sm font-bold text-[#5d4037] mb-1.5"
                >
                  수량 (최소 1, 최대 10)
                </label>
                <div className="flex items-center gap-2">
                  <button
                    type="button"
                    onClick={() => setQuantity((q) => Math.max(1, q - 1))}
                    disabled={quantity <= 1}
                    className="w-10 h-10 flex items-center justify-center rounded-lg bg-[#efebe9] text-[#5d4037] font-bold hover:bg-[#d7ccc8] disabled:opacity-40 transition-colors cursor-pointer"
                  >
                    -
                  </button>
                  <input
                    id="quantityInput"
                    type="number"
                    min={1}
                    max={10}
                    value={quantity}
                    onChange={(e) => {
                      const val = parseInt(e.target.value, 10);
                      if (isNaN(val)) setQuantity(1);
                      else setQuantity(Math.min(10, Math.max(1, val)));
                    }}
                    className="cafe-input text-center font-bold text-base"
                  />
                  <button
                    type="button"
                    onClick={() => setQuantity((q) => Math.min(10, q + 1))}
                    disabled={quantity >= 10}
                    className="w-10 h-10 flex items-center justify-center rounded-lg bg-[#efebe9] text-[#5d4037] font-bold hover:bg-[#d7ccc8] disabled:opacity-40 transition-colors cursor-pointer"
                  >
                    +
                  </button>
                </div>
              </div>

              {/* 7. 요청사항 (textarea) */}
              <div>
                <label 
                  htmlFor="requestsInput" 
                  className="block text-sm font-bold text-[#5d4037] mb-1.5"
                >
                  요청사항
                </label>
                <textarea
                  id="requestsInput"
                  rows={3}
                  placeholder="예: 얼음 적게 넣어주세요, 텀블러에 담아주세요"
                  value={requests}
                  onChange={(e) => setRequests(e.target.value)}
                  className="cafe-input resize-none"
                />
              </div>

              {/* 유효성 검사 경고 인라인 메시지 */}
              {validationError && (
                <div className="flex items-center gap-2 p-3 bg-red-50 text-red-700 text-sm rounded-lg border border-red-200">
                  <AlertCircle className="w-4 h-4 shrink-0" />
                  <span>{validationError}</span>
                </div>
              )}

              {/* 실시간 예상 금액 표시 */}
              <div className="pt-2 text-center border-t border-[#f3ece2]">
                <div className="text-xs text-[#8d6e63] font-medium mb-1">
                  실시간 계산 금액
                </div>
                <div className="text-[24px] font-bold text-[#6b4226] tracking-tight">
                  예상 금액: {estimatedPrice.toLocaleString()}원
                </div>
              </div>

              {/* 주문하기 버튼 & 다시 작성 버튼 */}
              <div className="space-y-2 pt-1">
                <button
                  type="submit"
                  disabled={isSubmitting}
                  className="w-full py-3.5 px-4 rounded-lg btn-order font-bold text-base shadow-md flex items-center justify-center gap-2 cursor-pointer disabled:opacity-50"
                >
                  {isSubmitting ? (
                    <>
                      <RefreshCw className="w-4 h-4 animate-spin" />
                      Supabase에 주문 등록 중...
                    </>
                  ) : (
                    <>
                      <Send className="w-4 h-4" />
                      주문하기 {connectionStatus === 'connected' && '(DB 실시간 연동)'}
                    </>
                  )}
                </button>
                
                <button
                  type="button"
                  onClick={handleReset}
                  className="w-full py-2.5 px-4 rounded-lg bg-[#efebe9] text-[#5d4037] hover:bg-[#d7ccc8] font-semibold text-sm transition-colors flex items-center justify-center gap-1.5 cursor-pointer"
                >
                  <RotateCcw className="w-3.5 h-3.5" />
                  다시 작성
                </button>
              </div>

              {/* 주문 확인 메시지 영역 */}
              {confirmationMessage && (
                <div className="p-4 bg-[#e8f5e9] text-[#2e7d32] border border-[#c8e6c9] rounded-lg text-sm font-medium flex items-start gap-3 shadow-sm transition-all animate-fadeIn">
                  <CheckCircle2 className="w-5 h-5 shrink-0 mt-0.5 text-[#2e7d32]" />
                  <div className="flex-1 leading-relaxed">
                    {confirmationMessage}
                  </div>
                </div>
              )}
            </form>
          </main>
        )}

        {/* 탭 2: 주문 게시판 (접수된 주문 목록 실시간 확인) */}
        {activeTab === 'board' && (
          <main className="p-6">
            <div className="flex items-center justify-between mb-4">
              <div>
                <h2 className="text-base font-bold text-[#5d4037] flex items-center gap-1.5">
                  실시간 주문 게시판
                  {connectionStatus === 'connected' && (
                    <span className="text-[10px] px-1.5 py-0.5 bg-emerald-100 text-emerald-800 rounded font-normal">
                      Supabase Live
                    </span>
                  )}
                </h2>
                <p className="text-xs text-[#8d6e63]">
                  {connectionStatus === 'connected'
                    ? 'Supabase 실시간 데이터베이스와 동기화됩니다.'
                    : '로컬 임시 모드 (상단 버튼을 눌러 Supabase에 연결하세요).'}
                </p>
              </div>
              <div className="flex items-center gap-1.5">
                {connectionStatus === 'connected' && (
                  <button
                    type="button"
                    onClick={loadOrdersFromDb}
                    disabled={isLoadingOrders}
                    className="p-1.5 rounded-lg border border-[#ede0d4] text-[#8d6e63] hover:text-[#5d4037] hover:bg-[#ede0d4]/50 transition-colors cursor-pointer"
                    title="주문 새로고침"
                  >
                    <RefreshCw className={`w-3.5 h-3.5 ${isLoadingOrders ? 'animate-spin' : ''}`} />
                  </button>
                )}
                <button
                  type="button"
                  onClick={() => setActiveTab('order')}
                  className="text-xs font-semibold px-3 py-1.5 rounded-lg bg-[#6b4226] text-white hover:bg-[#855331] transition-colors cursor-pointer"
                >
                  + 새 주문하기
                </button>
              </div>
            </div>

            {isLoadingOrders ? (
              <div className="text-center py-12 text-[#a1887f]">
                <RefreshCw className="w-8 h-8 mx-auto mb-2 animate-spin text-[#6b4226]" />
                <p className="text-sm">Supabase에서 주문 목록을 불러오는 중...</p>
              </div>
            ) : orderList.length === 0 ? (
              <div className="text-center py-12 text-[#a1887f]">
                <Coffee className="w-10 h-10 mx-auto mb-2 opacity-40" />
                <p className="text-sm">접수된 주문이 없습니다.</p>
              </div>
            ) : (
              <div className="space-y-3">
                {orderList.map((order, idx) => (
                  <div
                    key={order.id || idx}
                    className="p-4 rounded-xl border border-[#ede0d4] bg-[#faf6f0] shadow-xs hover:border-[#6b4226]/40 transition-colors"
                  >
                    <div className="flex items-center justify-between border-b border-[#ebdccd] pb-2 mb-2">
                      <div className="flex items-center gap-2">
                        <span className="font-bold text-[#5d4037] text-sm">
                          {order.customerName}님
                        </span>
                        {order.phoneNumber && (
                          <span className="text-xs text-[#8d6e63]">
                            ({order.phoneNumber})
                          </span>
                        )}
                        {order.dbId && (
                          <span className="text-[10px] text-[#a1887f] font-mono">
                            #{order.dbId}
                          </span>
                        )}
                      </div>

                      {/* 상태 변경 칩 버튼 그룹 */}
                      <div className="flex items-center gap-1">
                        {(['접수완료', '제조중', '완료'] as const).map((st) => (
                          <button
                            key={st}
                            type="button"
                            onClick={() => handleUpdateStatus(order, st)}
                            className={`text-[11px] px-2 py-0.5 rounded cursor-pointer transition-all ${
                              order.orderStatus === st
                                ? st === '완료'
                                  ? 'bg-[#2e7d32] text-white font-bold shadow-xs'
                                  : st === '제조중'
                                  ? 'bg-[#ef6c00] text-white font-bold shadow-xs'
                                  : 'bg-[#6b4226] text-white font-bold shadow-xs'
                                : 'bg-white/80 text-[#8d6e63] hover:bg-white border border-[#ebdccd]'
                            }`}
                            title={`클릭하여 '${st}' 상태로 변경`}
                          >
                            {st}
                          </button>
                        ))}

                        <button
                          type="button"
                          onClick={() => handleDeleteOrder(order)}
                          className="p-1 rounded text-[#a1887f] hover:text-red-600 hover:bg-red-50 transition-colors cursor-pointer ml-1"
                          title="주문 삭제"
                        >
                          <Trash2 className="w-3.5 h-3.5" />
                        </button>
                      </div>
                    </div>

                    <div className="text-sm font-semibold text-[#3e2723] mb-1">
                      {order.drinkName} · {order.size}사이즈 · {order.quantity}잔
                    </div>

                    {order.options.length > 0 && (
                      <div className="text-xs text-[#6d4c41] mb-1">
                        추가 옵션: {order.options.join(', ')}
                      </div>
                    )}

                    {order.requests && (
                      <div className="text-xs text-[#795548] bg-white p-2 rounded border border-[#ede0d4] mb-2 italic">
                        &quot;{order.requests}&quot;
                      </div>
                    )}

                    <div className="flex items-center justify-between pt-1 text-xs">
                      <span className="text-[#8d6e63] flex items-center gap-1">
                        <Clock className="w-3 h-3" />
                        {order.createdAt}
                      </span>
                      <span className="text-sm font-bold text-[#6b4226]">
                        {order.totalPrice.toLocaleString()}원
                      </span>
                    </div>
                  </div>
                ))}
              </div>
            )}
          </main>
        )}

        {/* 푸터 영역 */}
        <footer className="px-6 py-4 bg-[#faf6f0] border-t border-[#ede0d4] flex items-center justify-between text-xs text-[#8d6e63]">
          <span>바이브 카페 · 3,500원부터 즐기는 프리미엄 원두 커피</span>
          <button
            type="button"
            onClick={() => setIsConfigModalOpen(true)}
            className="text-[11px] underline text-[#6b4226] hover:text-[#855331] cursor-pointer"
          >
            Supabase 설정
          </button>
        </footer>
      </div>

      {/* Supabase 연동 설정 모달 */}
      <SupabaseModal
        isOpen={isConfigModalOpen}
        onClose={() => setIsConfigModalOpen(false)}
        onConfigChanged={checkConnection}
        sqlQuery={SUPABASE_SQL_QUERY}
      />
    </div>
  );
}
